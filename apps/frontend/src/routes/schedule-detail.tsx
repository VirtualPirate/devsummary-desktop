import { Link, useNavigate, useParams } from "@tanstack/react-router";
import { ArrowLeft, Pause, Play, Trash2 } from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from "@/components/ui/alert-dialog";
import { PageHeader } from "@/components/devsummary/shared/page-header";
import {
  ErrorState,
  extractErrorMessage,
} from "@/components/devsummary/shared/error-state";
import { SkeletonList } from "@/components/devsummary/shared/skeleton-list";
import { ScheduleForm } from "@/components/devsummary/schedules/schedule-form";
import {
  useDeleteBriefSchedule,
  useGetBriefSchedule,
  usePauseBriefSchedule,
  useResumeBriefSchedule,
} from "@/hooks/api/use-brief-schedules";

export function ScheduleDetailPage() {
  const { scheduleId } = useParams({ strict: false });
  const navigate = useNavigate();

  const scheduleQuery = useGetBriefSchedule(scheduleId);
  const pauseMutation = usePauseBriefSchedule();
  const resumeMutation = useResumeBriefSchedule();
  const deleteMutation = useDeleteBriefSchedule();

  const [confirmDeleteOpen, setConfirmDeleteOpen] = useState(false);

  if (scheduleQuery.isLoading) {
    return (
      <div className="mx-auto max-w-3xl">
        <PageHeader title="…" />
        <SkeletonList rows={6} rowHeight={36} />
      </div>
    );
  }
  if (scheduleQuery.isError || !scheduleQuery.data?.data) {
    return (
      <div className="mx-auto max-w-3xl">
        <PageHeader title="Schedule" />
        <ErrorState
          message={extractErrorMessage(scheduleQuery.error)}
          onRetry={() => scheduleQuery.refetch()}
        />
      </div>
    );
  }

  const schedule = scheduleQuery.data.data;

  const handleToggle = async () => {
    try {
      if (schedule.paused) {
        await resumeMutation.mutateAsync(schedule.id);
        toast.success("Schedule resumed");
      } else {
        await pauseMutation.mutateAsync(schedule.id);
        toast.success("Schedule paused");
      }
    } catch (err) {
      toast.error(extractErrorMessage(err));
    }
  };

  const handleDelete = async () => {
    try {
      await deleteMutation.mutateAsync(schedule.id);
      toast.success("Schedule deleted");
      await navigate({ to: "/schedules" });
    } catch (err) {
      toast.error(extractErrorMessage(err));
    }
  };

  return (
    // Matches /schedules/new: same fields, same single column.
    <div className="mx-auto max-w-3xl">
      <div className="mb-3">
        <Link
          to="/schedules"
          className="inline-flex items-center gap-1 text-xs text-muted-foreground hover:text-foreground"
        >
          <ArrowLeft className="size-3" /> Back to schedules
        </Link>
      </div>

      <PageHeader
        eyebrow="Schedule"
        title={schedule.name}
        description={
          schedule.paused
            ? "Paused — future runs are on hold."
            : "Active — running on schedule."
        }
        actions={
          <>
            <Button size="sm" variant="outline" onClick={handleToggle}>
              {schedule.paused ? (
                <>
                  <Play className="size-3.5" /> Resume
                </>
              ) : (
                <>
                  <Pause className="size-3.5" /> Pause
                </>
              )}
            </Button>
            <Button
              size="sm"
              variant="outline"
              className="text-destructive hover:text-destructive"
              onClick={() => setConfirmDeleteOpen(true)}
            >
              <Trash2 className="size-3.5" /> Delete
            </Button>
          </>
        }
      />

      <ScheduleForm existing={schedule} />

      <AlertDialog open={confirmDeleteOpen} onOpenChange={setConfirmDeleteOpen}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Delete this schedule?</AlertDialogTitle>
            <AlertDialogDescription>
              Briefs already generated by this schedule stay. Future runs stop.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel>Cancel</AlertDialogCancel>
            <AlertDialogAction onClick={handleDelete} disabled={deleteMutation.isPending}>
              Delete
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
  );
}
