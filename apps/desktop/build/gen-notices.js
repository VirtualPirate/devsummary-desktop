'use strict';

const path = require('node:path');
const fs = require('node:fs');
const { execFileSync } = require('node:child_process');

/**
 * Every pnpm invocation in the packaging path goes through here.
 *
 * Windows has no `pnpm` executable to spawn: npm installs it as a set of shims
 * (pnpm.cmd, pnpm.ps1) whose exact membership depends on how pnpm was put
 * there, and execFile has refused to spawn a .cmd at all since Node's
 * CVE-2024-27980 fix. Naming `pnpm.cmd` explicitly just moves the guess — the
 * windows-latest runner still came back with `status: null`, i.e. the spawn
 * never happened. Going through the shell lets the OS resolve whichever shim
 * actually exists. Arguments are quoted for that path because a checkout under
 * e.g. "Program Files" would otherwise split into two.
 *
 * The catch exists because the default failure is useless on an unattended
 * runner: execFileSync puts none of the child's output in the message, and pnpm
 * reports its errors on stdout rather than stderr, so the first two CI rounds
 * failed here with nothing to act on beyond "Command failed".
 */
function runPnpm(args, opts = {}) {
  const viaShell = process.platform === 'win32';
  const argv = viaShell ? args.map((a) => (/[\s"]/.test(a) ? `"${a}"` : a)) : args;

  try {
    return execFileSync('pnpm', argv, { shell: viaShell, ...opts });
  } catch (err) {
    const how = [
      `exit=${err.status}`,
      err.signal ? `signal=${err.signal}` : null,
      err.code ? `code=${err.code}` : null,
    ]
      .filter(Boolean)
      .join(' ');
    const output = [err.stdout, err.stderr]
      .map((s) => (s || '').toString().trim())
      .filter(Boolean)
      .join('\n');
    throw new Error(
      `\`pnpm ${args.join(' ')}\` failed (${how})${output ? `:\n${output}` : ' with no output'}`,
    );
  }
}

/**
 * Regenerates THIRD-PARTY-NOTICES.md at the repo root — the attribution file the
 * installer ships (electron-builder.yml `extraResources`). Run from beforePack.js
 * so a shipped build can never carry notices that predate a dependency change.
 *
 * MIT, BSD and Apache-2.0 — which is every license in this tree — all permit
 * redistribution only if their notice travels with the binary, so the *text* is
 * what matters, not a list of SPDX ids.
 *
 * Source of truth is `pnpm licenses list --prod`, which walks the installed
 * workspace and reports the on-disk path of every production package; the license
 * text is then read out of that directory.
 *
 * ponytail: over-inclusive on purpose. `--prod` reports production dependencies of
 * every workspace project, so a frontend dep that the bundler tree-shakes out still
 * gets attributed, and a devDependency pulled in transitively can appear too.
 * Listing a package that did not ship is harmless; omitting one that did is the
 * license violation. Narrow it only if the file's size becomes a real problem.
 */
function generate(repoRoot) {
  const raw = runPnpm(['licenses', 'list', '--json', '--prod'], {
    cwd: repoRoot,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });

  /** @type {Record<string, Array<{name: string, versions: string[], paths: string[], license: string, author?: string, homepage?: string}>>} */
  const byLicense = JSON.parse(raw);
  const packages = Object.values(byLicense)
    .flat()
    .sort((a, b) => a.name.localeCompare(b.name));

  const unknown = packages.filter((p) => !p.license || /unknown|unlicensed/i.test(p.license));
  if (unknown.length > 0) {
    // Not a nit: a dependency with no declared license grants no redistribution
    // right at all, so shipping one is the thing this file exists to prevent.
    throw new Error(
      `[gen-notices] no license declared for: ${unknown.map((p) => p.name).join(', ')}`,
    );
  }

  const electron = electronNotice(repoRoot);
  const sections = [electron, ...packages.map(toSection)];
  const noText = sections.filter((s) => !s.text).map((s) => s.title);

  const body = [
    '# Third-party notices',
    '',
    `DevSummary bundles the software listed below. Generated by \`apps/desktop/build/gen-notices.js\``,
    'from the installed dependency tree — edit that script, not this file.',
    '',
    `${sections.length} components. Chromium's own notices are a separate file,`,
    '`LICENSES.chromium.html`, shipped beside this one.',
    '',
    noText.length > 0
      ? `Components whose package ships no license file are listed with their declared\nSPDX identifier instead: ${noText.join(', ')}.\n`
      : '',
    '---',
    '',
    ...sections.map(
      (s) =>
        `## ${s.title}\n\n` +
        `License: ${s.license}${s.homepage ? ` · ${s.homepage}` : ''}\n\n` +
        (s.text
          ? '```\n' + s.text.replace(/```/g, "'''").trimEnd() + '\n```\n'
          : `No license text is distributed with this package. See the SPDX identifier above.\n`),
    ),
  ].join('\n');

  const out = path.join(repoRoot, 'THIRD-PARTY-NOTICES.md');
  fs.writeFileSync(out, body);
  console.log(`[gen-notices] ${sections.length} components -> ${path.relative(repoRoot, out)}`);
  return out;
}

/** The license file a package ships, under whatever name it chose. */
function readLicenseText(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir);
  } catch {
    return null; // pnpm reported a path that is gone — a stale store entry.
  }
  const match = entries
    .filter((name) => /^(licen[cs]e|copying|notice)/i.test(name))
    .sort((a, b) => a.length - b.length)[0];
  if (!match) return null;
  const full = path.join(dir, match);
  return fs.statSync(full).isFile() ? fs.readFileSync(full, 'utf8') : null;
}

function toSection(pkg) {
  return {
    title: `${pkg.name} ${pkg.versions.join(', ')}`,
    license: pkg.license,
    homepage: pkg.homepage,
    text: pkg.paths.map(readLicenseText).find(Boolean) ?? null,
  };
}

/**
 * Electron is a devDependency — it is the runtime the app ships inside, so
 * `pnpm licenses --prod` never sees it and it has to be added by hand. Its MIT
 * license covers Electron itself; Chromium and the hundreds of components inside
 * it are covered by LICENSES.chromium.html, 20 MB that belongs in the installer
 * rather than inlined here.
 */
function electronNotice(repoRoot) {
  const dir = path.join(repoRoot, 'apps', 'desktop', 'node_modules', 'electron');
  const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
  return {
    title: `electron ${version}`,
    license: 'MIT',
    homepage: 'https://github.com/electron/electron',
    text: readLicenseText(path.join(dir, 'dist')) ?? readLicenseText(dir),
  };
}

module.exports = { generate, runPnpm };

if (require.main === module) {
  generate(path.resolve(__dirname, '..', '..', '..'));
}
